const fs=require('fs'),ts=require('typescript'),vm=require('vm'),assert=require('node:assert/strict');
const out={};vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/voucherSourceBalance.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:out});
const {receiptSizeBreakdown,cuttingSourceBalance}=out;
assert.equal(receiptSizeBreakdown(49,[{size:'S',qty:100}])[0].qty,49);
assert.equal(receiptSizeBreakdown(48,[{size:'S',qty:100}])[0].qty,48);
assert.throws(()=>receiptSizeBreakdown(49,[{size:'S',qty:50},{size:'M',qty:50}]),/multiple sizes/);
assert.equal(receiptSizeBreakdown(100,[{size:'S',qty:50},{size:'M',qty:50}]).length,2);
const issues=[{cuttingComponentId:'cut48',size:'S',issuedQty:48}];
const source={id:'cut49',net_pieces:49,size_breakdown:[{size:'S',qty:49}]};
assert.equal(cuttingSourceBalance(source,issues,'S').remaining,49);
issues.push({cuttingComponentId:'cut49',size:'S',issuedQty:20});
assert.equal(cuttingSourceBalance(source,issues,'S').remaining,29);
assert.equal(cuttingSourceBalance(source,issues,'M').remaining,0);
assert.equal(cuttingSourceBalance(undefined,issues,'S').remaining,0);
assert.equal(cuttingSourceBalance({id:'cut49',net_pieces:30,size_breakdown:[{size:'S',qty:40}]},issues,'S').remaining,10);
console.log('PASS: partial single-size receipts, ambiguous multi-size rejected, cutting source isolation, size limits, net cap, missing source.');
